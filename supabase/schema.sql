CREATE TABLE IF NOT EXISTS public.roles (
  id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo        public.tipo_rol NOT NULL UNIQUE,
  descripcion text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.responsables (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  auth_user_id    uuid UNIQUE REFERENCES auth.users (id) ON DELETE SET NULL,
  nombre          varchar(120) NOT NULL,
  apellido        varchar(120) NOT NULL,
  dni             varchar(20)  NOT NULL UNIQUE,
  email           varchar(255) NOT NULL UNIQUE,
  id_rol          smallint NOT NULL REFERENCES public.roles (id),
  estado          public.estado_entidad NOT NULL DEFAULT 'activo',
  registrado      boolean NOT NULL DEFAULT false,
  invitado_en     timestamptz,
  registrado_en   timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.proveedores (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  cod_proveedor  varchar(40)  NOT NULL UNIQUE,
  razon_social   varchar(255) NOT NULL,
  estado         public.estado_entidad NOT NULL DEFAULT 'activo',
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.depositos (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_responsable  uuid REFERENCES public.responsables (id) ON DELETE SET NULL,
  codigo          varchar(40)  NOT NULL UNIQUE,
  nombre          varchar(160) NOT NULL,
  ubicacion       varchar(255) NOT NULL,
  cant_articulos  integer      NOT NULL DEFAULT 0 CHECK (cant_articulos >= 0),
  costo_total     numeric(18, 2) NOT NULL DEFAULT 0 CHECK (costo_total >= 0),
  estado          public.estado_entidad NOT NULL DEFAULT 'activo',
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.familias (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo       varchar(10)  NOT NULL UNIQUE,
  descripcion  varchar(255) NOT NULL,
  estado       public.estado_entidad NOT NULL DEFAULT 'activo',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.grupos (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_familia   uuid NOT NULL REFERENCES public.familias (id) ON DELETE RESTRICT,
  codigo       varchar(20)  NOT NULL,
  descripcion  varchar(255) NOT NULL,
  estado       public.estado_entidad NOT NULL DEFAULT 'activo',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_familia, codigo)
);

CREATE TABLE IF NOT EXISTS public.articulos (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_grupo          uuid REFERENCES public.grupos (id) ON DELETE SET NULL,
  codigo            varchar(40)  NOT NULL UNIQUE,
  nombre            varchar(255) NOT NULL,
  unidad_de_medida  varchar(40)  NOT NULL,
  estado            public.estado_entidad NOT NULL DEFAULT 'activo',
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.inventario_depositos (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_deposito      uuid NOT NULL REFERENCES public.depositos (id) ON DELETE RESTRICT,
  id_articulo      uuid NOT NULL REFERENCES public.articulos (id) ON DELETE RESTRICT,
  cantidad_actual  integer NOT NULL DEFAULT 0,
  updated_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_deposito, id_articulo)
);

CREATE TABLE IF NOT EXISTS public.costos_articulos (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_articulo     uuid NOT NULL REFERENCES public.articulos (id) ON DELETE RESTRICT,
  fecha           timestamptz NOT NULL DEFAULT now(),
  costo           numeric(18, 4) NOT NULL CHECK (costo >= 0),
  id_responsable  uuid REFERENCES public.responsables (id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.tipos_movimiento (
  id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo        public.tipo_movimiento NOT NULL UNIQUE,
  descripcion text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.movimientos (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_tipo              smallint NOT NULL REFERENCES public.tipos_movimiento (id),
  id_responsable       uuid NOT NULL REFERENCES public.responsables (id),
  id_deposito_origen   uuid REFERENCES public.depositos (id),
  id_deposito_destino  uuid REFERENCES public.depositos (id),
  id_proveedor         uuid REFERENCES public.proveedores (id),
  es_devolucion        boolean NOT NULL DEFAULT false,
  motivo               text,
  fecha                timestamptz NOT NULL DEFAULT now(),
  nro_remito           varchar(80) NOT NULL,
  fotos_remito         text[] NOT NULL DEFAULT '{}',
  cant_total_articulos integer NOT NULL DEFAULT 0 CHECK (cant_total_articulos >= 0),
  created_at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_movimiento_depositos_distintos
    CHECK (
      id_deposito_origen IS NULL
      OR id_deposito_destino IS NULL
      OR id_deposito_origen <> id_deposito_destino
    )
);

CREATE TABLE IF NOT EXISTS public.movimientos_articulos (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  id_movimiento  uuid NOT NULL REFERENCES public.movimientos (id) ON DELETE CASCADE,
  id_articulo    uuid NOT NULL REFERENCES public.articulos (id) ON DELETE RESTRICT,
  cantidad       integer NOT NULL CHECK (cantidad > 0),
  observacion    text,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.tipos_notificacion (
  id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo        public.tipo_notificacion NOT NULL UNIQUE,
  descripcion text,
