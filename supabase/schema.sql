CREATE OR REPLACE VIEW public.v_articulos_costo_actual AS
SELECT
  a.*,
  g.codigo AS grupo_codigo,
  g.descripcion AS grupo_descripcion,
  f.id AS id_familia,
  f.codigo AS familia_codigo,
  f.descripcion AS familia_descripcion,
  public.fn_costo_actual_articulo(a.id) AS costo_actual
FROM public.articulos a
LEFT JOIN public.grupos g ON g.id = a.id_grupo
LEFT JOIN public.familias f ON f.id = g.id_familia;

CREATE OR REPLACE VIEW public.v_familias_resumen AS
SELECT
  f.id,
  f.codigo,
  f.descripcion,
  f.estado,
  COUNT(DISTINCT g.id) FILTER (WHERE g.estado = 'activo') AS cant_grupos,
  COUNT(DISTINCT a.id) FILTER (WHERE a.estado = 'activo') AS cant_articulos,
  COALESCE(SUM(public.fn_costo_actual_articulo(a.id)) FILTER (WHERE a.estado = 'activo'), 0) AS costo_total
FROM public.familias f
LEFT JOIN public.grupos g ON g.id_familia = f.id
LEFT JOIN public.articulos a ON a.id_grupo = g.id
GROUP BY f.id;

CREATE OR REPLACE VIEW public.v_grupos_resumen AS
SELECT
  g.id,
  g.id_familia,
  g.codigo,
  g.descripcion,
  g.estado,
  COUNT(a.id) FILTER (WHERE a.estado = 'activo') AS cant_articulos,
  COALESCE(SUM(public.fn_costo_actual_articulo(a.id)) FILTER (WHERE a.estado = 'activo'), 0) AS costo_total
FROM public.grupos g
LEFT JOIN public.articulos a ON a.id_grupo = g.id
GROUP BY g.id;

