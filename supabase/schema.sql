CREATE OR REPLACE FUNCTION public.fn_diff_registros(p_old jsonb, p_new jsonb, p_omitir text[])
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  v_key text;
  v_partes text[] := ARRAY[]::text[];
BEGIN
  FOR v_key IN SELECT jsonb_object_keys(p_new)
  LOOP
    IF v_key = ANY (p_omitir) THEN
      CONTINUE;
    END IF;
    IF (p_old -> v_key) IS DISTINCT FROM (p_new -> v_key) THEN
      v_partes := array_append(
        v_partes,
        format(
          '%s: %s → %s',
          v_key,
          COALESCE(p_old ->> v_key, 'null'),
          COALESCE(p_new ->> v_key, 'null')
        )
      );
    END IF;
  END LOOP;

  RETURN array_to_string(v_partes, '; ');
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_insertar_notificacion(
  p_tipo public.tipo_notificacion,
  p_descripcion text,
  p_tabla text DEFAULT NULL,
  p_valor uuid DEFAULT NULL,
  p_responsable uuid DEFAULT NULL,
  p_responsable_extra uuid DEFAULT NULL,
  p_metadata jsonb DEFAULT '{}'::jsonb
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_id uuid;
  v_tipo_id smallint;
BEGIN
  SELECT id INTO v_tipo_id FROM public.tipos_notificacion WHERE tipo = p_tipo;
  IF v_tipo_id IS NULL THEN
    RAISE EXCEPTION 'Tipo de notificación inexistente: %', p_tipo;
  END IF;

  INSERT INTO public.notificaciones (
    id_tipo_notificacion,
    id_responsable,
    id_responsable_extra,
    tabla_afectada,
    id_valor_ajustado,
    descripcion,
    metadata
  ) VALUES (
    v_tipo_id,
    COALESCE(p_responsable, public.fn_responsable_id_actual()),
    p_responsable_extra,
    p_tabla,
    p_valor,
    p_descripcion,
    COALESCE(p_metadata, '{}'::jsonb)
  )
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

-- Trigger genérico de auditoría (INSERT/UPDATE en maestros).
-- En UPDATE, estado activo→inactivo se trata como Eliminación (borrado lógico).
-- Solo se usa to_jsonb(NEW/OLD) para soportar tablas con columnas distintas.
CREATE OR REPLACE FUNCTION public.fn_trg_notificar_maestro()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_label text;
  v_diff text;
  v_omitir text[] := ARRAY['updated_at', 'created_at', 'invitado_en', 'registrado_en'];
  v_extra uuid;
  v_rol_old text;
  v_rol_new text;
  v_row jsonb;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_row := to_jsonb(NEW);
    v_label := COALESCE(
      v_row ->> 'codigo',
      v_row ->> 'cod_proveedor',
      v_row ->> 'nombre',
      v_row ->> 'razon_social',
      v_row ->> 'descripcion',
      v_row ->> 'dni',
      NEW.id::text
    );

    IF TG_TABLE_NAME = 'costos_articulos' THEN
      PERFORM public.fn_insertar_notificacion(
        'Creacion',
        format('Se registró un nuevo costo %s para el artículo %s', NEW.costo, NEW.id_articulo),
        'costos_articulos',
        NEW.id,
        NEW.id_responsable,
        NULL,
        jsonb_build_object('id_articulo', NEW.id_articulo, 'costo', NEW.costo)
      );
    ELSIF TG_TABLE_NAME = 'responsables' THEN
      PERFORM public.fn_insertar_notificacion(
        'Creacion',
        format('Se creó el responsable %s %s (DNI %s)', NEW.nombre, NEW.apellido, NEW.dni),
        'responsables',
        NEW.id,
        public.fn_responsable_id_actual(),
        NEW.id,
        jsonb_build_object('dni', NEW.dni, 'email', NEW.email)
      );
    ELSE
      PERFORM public.fn_insertar_notificacion(
        'Creacion',
        format('Alta en %s: %s', TG_TABLE_NAME, v_label),
        TG_TABLE_NAME,
        NEW.id
      );
    END IF;

    RETURN NEW;
  END IF;

  -- UPDATE
  IF TG_TABLE_NAME = 'responsables' AND OLD.id_rol IS DISTINCT FROM NEW.id_rol THEN
    SELECT tipo::text INTO v_rol_old FROM public.roles WHERE id = OLD.id_rol;
    SELECT tipo::text INTO v_rol_new FROM public.roles WHERE id = NEW.id_rol;
    PERFORM public.fn_insertar_notificacion(
      'Asignacion_Rol',
      format(
        'Se asignó el rol %s al responsable %s %s, que anteriormente tenía el rol %s',
        v_rol_new, NEW.nombre, NEW.apellido, v_rol_old
      ),
      'responsables',
      NEW.id,
      public.fn_responsable_id_actual(),
      NEW.id,
      jsonb_build_object('rol_anterior', v_rol_old, 'rol_nuevo', v_rol_new)
    );
  END IF;

  IF TG_TABLE_NAME = 'responsables' THEN
    v_omitir := v_omitir || ARRAY['id_rol', 'auth_user_id', 'registrado'];
    v_extra := NEW.id;
  END IF;

  IF TG_TABLE_NAME = 'depositos' THEN
    v_omitir := v_omitir || ARRAY['cant_articulos', 'costo_total'];
  END IF;

  IF to_jsonb(OLD) ? 'estado'
     AND (to_jsonb(OLD) ->> 'estado') = 'activo'
     AND (to_jsonb(NEW) ->> 'estado') = 'inactivo' THEN
    v_label := COALESCE(
      to_jsonb(NEW) ->> 'codigo',
      to_jsonb(NEW) ->> 'cod_proveedor',
      to_jsonb(NEW) ->> 'nombre',
      to_jsonb(NEW) ->> 'razon_social',
      to_jsonb(NEW) ->> 'dni',
      NEW.id::text
    );
    PERFORM public.fn_insertar_notificacion(
      'Eliminacion',
      format('Borrado lógico en %s: %s', TG_TABLE_NAME, v_label),
      TG_TABLE_NAME,
      NEW.id,
      public.fn_responsable_id_actual(),
      v_extra
    );
    RETURN NEW;
  END IF;

  v_diff := public.fn_diff_registros(to_jsonb(OLD), to_jsonb(NEW), v_omitir);
  IF v_diff IS NULL OR btrim(v_diff) = '' THEN
    RETURN NEW;
  END IF;

  PERFORM public.fn_insertar_notificacion(
    'Modificacion',
    format('Modificación en %s: %s', TG_TABLE_NAME, v_diff),
    TG_TABLE_NAME,
    NEW.id,
    public.fn_responsable_id_actual(),
    v_extra,
    jsonb_build_object('cambios', v_diff)
  );

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_trg_notificar_movimiento()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_mov public.movimientos%ROWTYPE;
  v_tipo text;
  v_origen text;
  v_destino text;
  v_depositos text;
BEGIN
  -- Relee el movimiento: el trigger es diferido y ya incluye el detalle.
  SELECT * INTO STRICT v_mov FROM public.movimientos WHERE id = NEW.id;
  SELECT tipo::text INTO v_tipo FROM public.tipos_movimiento WHERE id = v_mov.id_tipo;
  SELECT nombre INTO v_origen FROM public.depositos WHERE id = v_mov.id_deposito_origen;
  SELECT nombre INTO v_destino FROM public.depositos WHERE id = v_mov.id_deposito_destino;

  IF v_tipo = 'Entrada' THEN
    v_depositos := COALESCE(v_destino, 'depósito destino');
  ELSE
    v_depositos := format('%s / %s', COALESCE(v_origen, '-'), COALESCE(v_destino, '-'));
  END IF;

  PERFORM public.fn_insertar_notificacion(
    'Carga_Movimiento',
    format(
      'Movimiento %s (%s). Remito %s. Depósitos: %s. Cantidad total: %s. Motivo: %s',
      v_tipo,
      v_mov.fecha,
      v_mov.nro_remito,
      v_depositos,
      v_mov.cant_total_articulos,
      COALESCE(v_mov.motivo, '-')
    ),
    'movimientos',
    v_mov.id,
    v_mov.id_responsable,
    NULL,
    jsonb_build_object(
      'tipo', v_tipo,
      'id_deposito_origen', v_mov.id_deposito_origen,
      'id_deposito_destino', v_mov.id_deposito_destino,
      'id_proveedor', v_mov.id_proveedor,
      'es_devolucion', v_mov.es_devolucion
    )
  );

  RETURN NEW;
END;
$$;

