CREATE OR REPLACE FUNCTION public.rpc_upsert_articulos_masivo(
  p_filas jsonb,
  p_notificar boolean DEFAULT true
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET statement_timeout = '120s'
AS $$
DECLARE
  v_created integer := 0;
  v_updated integer := 0;
  v_unchanged integer := 0;
  v_total integer := 0;
  v_bad_cod text;
  v_bad_fam text;
  v_bad_gru text;
BEGIN
  IF NOT public.fn_es_administrador() THEN
    RAISE EXCEPTION 'Solo un administrador puede hacer carga masiva';
  END IF;

  IF p_filas IS NULL OR jsonb_typeof(p_filas) <> 'array' OR jsonb_array_length(p_filas) = 0 THEN
    RAISE EXCEPTION 'No hay filas para cargar';
  END IF;

  PERFORM set_config('app.carga_masiva', '1', true);
  SET LOCAL statement_timeout = '120s';

  CREATE TEMP TABLE tmp_art_carga (
    codigo text NOT NULL,
    nombre text NOT NULL,
    unidad text NOT NULL,
    familia_codigo text NOT NULL,
    grupo_codigo text NOT NULL,
    is_epp boolean NOT NULL,
    id_grupo uuid,
    id_articulo uuid
  ) ON COMMIT DROP;

  INSERT INTO tmp_art_carga (codigo, nombre, unidad, familia_codigo, grupo_codigo, is_epp)
  SELECT
    btrim(COALESCE(value ->> 'codigo', '')),
    btrim(COALESCE(value ->> 'nombre', '')),
    btrim(COALESCE(value ->> 'unidad_de_medida', '')),
    btrim(COALESCE(value ->> 'familia_codigo', '')),
    btrim(COALESCE(value ->> 'grupo_codigo', '')),
    CASE
      WHEN jsonb_typeof(value -> 'is_epp') = 'boolean' THEN (value -> 'is_epp')::text::boolean
      WHEN lower(btrim(COALESCE(value ->> 'is_epp', ''))) IN ('x', 'true', 't', '1', 'si', 'sí', 'yes', 'epp') THEN true
      ELSE false
    END
  FROM jsonb_array_elements(p_filas);

  GET DIAGNOSTICS v_total = ROW_COUNT;

  IF EXISTS (
    SELECT 1 FROM tmp_art_carga
    WHERE codigo = '' OR nombre = '' OR unidad = ''
  ) THEN
    RAISE EXCEPTION 'Hay filas incompletas en la carga masiva de artículos';
  END IF;

  IF EXISTS (
    SELECT 1 FROM tmp_art_carga
    WHERE (familia_codigo = '') <> (grupo_codigo = '')
  ) THEN
    SELECT codigo INTO v_bad_cod
    FROM tmp_art_carga
    WHERE (familia_codigo = '') <> (grupo_codigo = '')
    LIMIT 1;
    RAISE EXCEPTION 'El artículo % tiene familia o grupo incompleto', v_bad_cod;
  END IF;

  IF EXISTS (
    SELECT 1 FROM tmp_art_carga GROUP BY lower(codigo) HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Hay códigos de artículo repetidos en el Excel';
  END IF;

  UPDATE tmp_art_carga t
  SET id_grupo = g.id
  FROM public.grupos g
  JOIN public.familias f ON f.id = g.id_familia
  WHERE t.familia_codigo <> ''
    AND lower(f.codigo) = lower(t.familia_codigo)
    AND (
      lower(g.codigo) = lower(t.grupo_codigo)
      OR lower(g.codigo) = lower(t.familia_codigo || t.grupo_codigo)
    );

  SELECT t.codigo, t.familia_codigo, t.grupo_codigo
  INTO v_bad_cod, v_bad_fam, v_bad_gru
  FROM tmp_art_carga t
  WHERE t.familia_codigo <> '' AND t.id_grupo IS NULL
  LIMIT 1;

  IF v_bad_cod IS NOT NULL THEN
    RAISE EXCEPTION 'No existe el grupo % en la familia % (artículo %)', v_bad_gru, v_bad_fam, v_bad_cod;
  END IF;

  UPDATE tmp_art_carga t
  SET id_articulo = a.id
  FROM public.articulos a
  WHERE lower(a.codigo) = lower(t.codigo);

  INSERT INTO public.articulos (codigo, nombre, unidad_de_medida, id_grupo, is_epp, estado)
  SELECT t.codigo, t.nombre, t.unidad, t.id_grupo, t.is_epp, 'activo'
  FROM tmp_art_carga t
  WHERE t.id_articulo IS NULL;

  GET DIAGNOSTICS v_created = ROW_COUNT;

  UPDATE public.articulos a
  SET nombre = t.nombre,
      unidad_de_medida = t.unidad,
      id_grupo = t.id_grupo,
      is_epp = t.is_epp
  FROM tmp_art_carga t
  WHERE a.id = t.id_articulo
    AND (
      a.nombre IS DISTINCT FROM t.nombre
      OR a.unidad_de_medida IS DISTINCT FROM t.unidad
      OR a.id_grupo IS DISTINCT FROM t.id_grupo
      OR a.is_epp IS DISTINCT FROM t.is_epp
    );

  GET DIAGNOSTICS v_updated = ROW_COUNT;

  v_unchanged := v_total - v_created - v_updated;

  IF p_notificar AND v_created + v_updated > 0 THEN
    PERFORM public.fn_insertar_notificacion(
      'Carga_Masiva',
      format(
        'Carga masiva de artículos: %s creados y %s editados.',
        v_created,
        v_updated
      ),
      'articulos',
      NULL,
      public.fn_responsable_id_actual(),
      NULL,
      jsonb_build_object(
        'tabla', 'articulos',
        'creados', v_created,
        'editados', v_updated,
        'sin_cambios', v_unchanged,
        'total', v_total
      )
    );
  END IF;

  RETURN jsonb_build_object(
    'created', v_created,
    'updated', v_updated,
    'unchanged', v_unchanged,
    'total', v_total
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.rpc_upsert_articulos_masivo(jsonb, boolean) TO authenticated;

CREATE OR REPLACE FUNCTION public.rpc_asignar_responsables_deposito(
  p_deposito uuid,
  p_responsables uuid[]
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_codigo text;
  v_nombre text;
  v_ids uuid[];
  v_antes uuid[] := ARRAY[]::uuid[];
  v_persona uuid;
  v_nombre_persona text;
  v_removed integer := 0;
  v_assigned integer := 0;
BEGIN
  IF NOT public.fn_es_administrador() THEN
    RAISE EXCEPTION 'Solo un administrador puede asignar responsables a un depósito';
  END IF;

  SELECT d.codigo, d.nombre
  INTO v_codigo, v_nombre
  FROM public.depositos d
  WHERE d.id = p_deposito;

  IF v_codigo IS NULL THEN
    RAISE EXCEPTION 'El depósito no existe';
  END IF;

  SELECT COALESCE(array_agg(DISTINCT x), ARRAY[]::uuid[])
  INTO v_ids
  FROM unnest(COALESCE(p_responsables, ARRAY[]::uuid[])) AS x
  WHERE x IS NOT NULL;

  SELECT COALESCE(array_agg(dr.id_responsable), ARRAY[]::uuid[])
  INTO v_antes
  FROM public.depositos_responsables dr
  WHERE dr.id_deposito = p_deposito;

  DELETE FROM public.depositos_responsables dr
  WHERE dr.id_deposito = p_deposito
    AND NOT (dr.id_responsable = ANY (v_ids));

  INSERT INTO public.depositos_responsables (id_deposito, id_responsable)
  SELECT p_deposito, u.id_responsable
  FROM unnest(v_ids) AS u(id_responsable)
  ON CONFLICT (id_deposito, id_responsable) DO NOTHING;

  FOREACH v_persona IN ARRAY v_ids
  LOOP
    IF NOT (v_persona = ANY (v_antes)) THEN
      v_assigned := v_assigned + 1;
      v_nombre_persona := COALESCE(public.fn_nombre_responsable(v_persona), 'un responsable');
      PERFORM public.fn_insertar_notificacion(
        'Asignacion_Responsable',
        format(
          'Se asignó a %s como responsable del depósito %s – %s.',
          v_nombre_persona,
          v_codigo,
          v_nombre
        ),
        'depositos',
        p_deposito,
        public.fn_responsable_id_actual(),
        v_persona,
        jsonb_build_object(
          'id_deposito', p_deposito,
          'id_responsable_asignado', v_persona
        )
      );
    END IF;
  END LOOP;

  FOREACH v_persona IN ARRAY v_antes
  LOOP
    IF NOT (v_persona = ANY (v_ids)) THEN
      v_removed := v_removed + 1;
      v_nombre_persona := COALESCE(public.fn_nombre_responsable(v_persona), 'un responsable');
      PERFORM public.fn_insertar_notificacion(
        'Desvinculacion_Responsable',
        format(
          'Se desvinculó a %s del depósito %s – %s.',
          v_nombre_persona,
          v_codigo,
          v_nombre
        ),
        'depositos',
        p_deposito,
        public.fn_responsable_id_actual(),
        v_persona,
        jsonb_build_object(
          'id_deposito', p_deposito,
          'id_responsable_desvinculado', v_persona
        )
      );
    END IF;
  END LOOP;

  RETURN jsonb_build_object(
    'assigned', v_assigned,
    'removed', v_removed
  );
END;
$$;

