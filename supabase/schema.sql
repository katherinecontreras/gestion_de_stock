-- Alta transaccional de un movimiento + detalle (atomicidad de N artículos).
CREATE OR REPLACE FUNCTION public.rpc_crear_movimiento(
  p_id_tipo smallint,
  p_id_deposito_origen uuid,
  p_id_deposito_destino uuid,
  p_id_proveedor uuid,
  p_es_devolucion boolean,
  p_motivo text,
  p_nro_remito text,
  p_fotos_remito text[],
  p_articulos jsonb
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_movimiento_id uuid;
  v_item jsonb;
  v_responsable uuid;
BEGIN
  IF p_articulos IS NULL OR jsonb_typeof(p_articulos) <> 'array' OR jsonb_array_length(p_articulos) = 0 THEN
    RAISE EXCEPTION 'El movimiento debe incluir al menos un artículo';
  END IF;

  v_responsable := public.fn_responsable_id_actual();
  IF v_responsable IS NULL THEN
    RAISE EXCEPTION 'No hay un responsable autenticado para cargar el movimiento';
  END IF;

  INSERT INTO public.movimientos (
    id_tipo,
    id_responsable,
    id_deposito_origen,
    id_deposito_destino,
    id_proveedor,
    es_devolucion,
    motivo,
    nro_remito,
    fotos_remito
  ) VALUES (
    p_id_tipo,
    v_responsable,
    p_id_deposito_origen,
    p_id_deposito_destino,
    p_id_proveedor,
    COALESCE(p_es_devolucion, false),
    p_motivo,
    btrim(p_nro_remito),
    COALESCE(p_fotos_remito, ARRAY[]::text[])
  )
  RETURNING id INTO v_movimiento_id;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_articulos)
  LOOP
    INSERT INTO public.movimientos_articulos (
      id_movimiento,
      id_articulo,
      cantidad,
      observacion
    ) VALUES (
      v_movimiento_id,
      (v_item ->> 'id_articulo')::uuid,
      (v_item ->> 'cantidad')::integer,
      nullif(v_item ->> 'observacion', '')
    );
  END LOOP;

  RETURN v_movimiento_id;
END;
$$;

GRANT EXECUTE ON FUNCTION public.rpc_crear_movimiento(
  smallint, uuid, uuid, uuid, boolean, text, text, text[], jsonb
) TO authenticated;

-- Borrado lógico de familia: inactiva grupos y deja artículos sin grupo.
CREATE OR REPLACE FUNCTION public.rpc_eliminar_familia(p_familia uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.fn_es_administrador() THEN
    RAISE EXCEPTION 'Solo un administrador puede eliminar familias';
  END IF;

  UPDATE public.articulos a
  SET id_grupo = NULL
  WHERE a.id_grupo IN (SELECT g.id FROM public.grupos g WHERE g.id_familia = p_familia);

  UPDATE public.grupos
  SET estado = 'inactivo'
  WHERE id_familia = p_familia
    AND estado = 'activo';

  UPDATE public.familias
  SET estado = 'inactivo'
  WHERE id = p_familia
    AND estado = 'activo';
END;
$$;

GRANT EXECUTE ON FUNCTION public.rpc_eliminar_familia(uuid) TO authenticated;

