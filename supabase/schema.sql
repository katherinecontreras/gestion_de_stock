CREATE OR REPLACE FUNCTION public.fn_responsable_id_actual()
RETURNS uuid
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_id uuid;
  v_setting text;
BEGIN
  SELECT r.id
    INTO v_id
  FROM public.responsables r
  WHERE r.auth_user_id = auth.uid()
    AND r.estado = 'activo'
  LIMIT 1;

  IF v_id IS NOT NULL THEN
    RETURN v_id;
  END IF;

  v_setting := nullif(current_setting('app.responsable_id', true), '');
  IF v_setting IS NOT NULL THEN
    RETURN v_setting::uuid;
  END IF;

  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_es_administrador()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.responsables r
    JOIN public.roles rol ON rol.id = r.id_rol
    WHERE r.auth_user_id = auth.uid()
      AND r.estado = 'activo'
      AND rol.tipo = 'Administrador'
  );
$$;

CREATE OR REPLACE FUNCTION public.fn_depositos_del_responsable(p_responsable uuid DEFAULT NULL)
RETURNS SETOF uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT d.id
  FROM public.depositos d
  WHERE d.estado = 'activo'
    AND d.id_responsable = COALESCE(p_responsable, public.fn_responsable_id_actual());
$$;

CREATE OR REPLACE FUNCTION public.fn_costo_actual_articulo(p_articulo uuid)
RETURNS numeric
LANGUAGE sql
STABLE
AS $$
  SELECT c.costo
  FROM public.costos_articulos c
  WHERE c.id_articulo = p_articulo
  ORDER BY c.fecha DESC, c.created_at DESC
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.fn_recalcular_totales_deposito(p_deposito uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_cant integer;
  v_costo numeric(18, 2);
BEGIN
  SELECT
    COALESCE(SUM(i.cantidad_actual), 0),
    COALESCE(SUM(i.cantidad_actual * COALESCE(public.fn_costo_actual_articulo(i.id_articulo), 0)), 0)
  INTO v_cant, v_costo
  FROM public.inventario_depositos i
  WHERE i.id_deposito = p_deposito;

  UPDATE public.depositos
  SET cant_articulos = v_cant,
      costo_total = ROUND(v_costo, 2),
      updated_at = now()
  WHERE id = p_deposito;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_ajustar_inventario(
  p_deposito uuid,
  p_articulo uuid,
  p_delta integer
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_cantidad integer;
BEGIN
  IF p_deposito IS NULL THEN
    RAISE EXCEPTION 'El depósito es obligatorio para ajustar inventario';
  END IF;

  INSERT INTO public.inventario_depositos (id_deposito, id_articulo, cantidad_actual)
  VALUES (p_deposito, p_articulo, p_delta)
  ON CONFLICT (id_deposito, id_articulo)
  DO UPDATE SET
    cantidad_actual = public.inventario_depositos.cantidad_actual + EXCLUDED.cantidad_actual,
    updated_at = now()
  RETURNING cantidad_actual INTO v_cantidad;

  IF v_cantidad < 0 THEN
    RAISE EXCEPTION 'Stock insuficiente en el depósito % para el artículo % (quedaría %)',
      p_deposito, p_articulo, v_cantidad;
  END IF;

  PERFORM public.fn_recalcular_totales_deposito(p_deposito);
END;
$$;

