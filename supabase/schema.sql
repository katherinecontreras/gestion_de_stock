  UPDATE public.articulos
  SET id_grupo = p_grupo
  WHERE id = ANY (v_ids)
    AND (id_grupo IS DISTINCT FROM p_grupo);
  GET DIAGNOSTICS v_assigned = ROW_COUNT;

  RETURN jsonb_build_object(
    'assigned', v_assigned,
    'removed', v_removed
  );
END;
