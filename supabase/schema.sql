CREATE OR REPLACE FUNCTION public.fn_diff_registros(p_old jsonb, p_new jsonb, p_omitir text[])
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  v_key text;
  v_partes text[] := ARRAY[]::text[];
BEGIN
  FOR v_key IN SELECT jsonb_object_keys(p_new)
  LOOP
    IF v_key = ANY (p_omitir) THEN
      CONTINUE;
    END IF;
    IF (p_old -> v_key) IS DISTINCT FROM (p_new -> v_key) THEN
      v_partes := array_append(
        v_partes,
        format(
          '%s: %s → %s',
          v_key,
          COALESCE(p_old ->> v_key, 'null'),
          COALESCE(p_new ->> v_key, 'null')
        )
      );
    END IF;
  END LOOP;

  RETURN array_to_string(v_partes, '; ');
END;
$$;

